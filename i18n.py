def normalize_language(code):
    """Map a locale string such as 'ko_KR', 'ja-JP' or 'zh-Hans-CN' to a supported code, or None."""
    if not code:
        return None
    code = str(code).strip().lower().replace("_", "-")
    primary = code.split("-")[0]
    if primary == "zh":
        # Traditional Chinese is not provided; only map Simplified variants.
        if any(part in ("hant", "tw", "hk", "mo") for part in code.split("-")[1:]):
            return None
        return "zh"
    if primary in SUPPORTED_LANGUAGES:
        return primary
    return None


def detect_system_language(preferred_languages=None):
    """Return the first supported language from the OS preference list, else English.

    preferred_languages: ordered list like ['ja-JP', 'en-US'] (Qt's QLocale.uiLanguages()).
    """
    candidates = list(preferred_languages or [])
    if not candidates:
        try:
            system_locale = locale.getlocale()[0]
        except (ValueError, TypeError):
            system_locale = None
        if system_locale:
            candidates.append(system_locale)
    for candidate in candidates:
        language = normalize_language(candidate)
        if language:
            return language
    return DEFAULT_LANGUAGE


def set_language(code):
    """Set the active UI language. Unknown codes fall back to English."""
    global _current_language
    _current_language = code if code in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE
    return _current_language


def current_language():
    return _current_language


def tr(key, **kwargs):
    """Translate a key into the active language and fill {placeholders}."""
    text = STRINGS.get(_current_language, {}).get(key)
    if text is None:
        text = STRINGS[DEFAULT_LANGUAGE].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            return text
    return text
